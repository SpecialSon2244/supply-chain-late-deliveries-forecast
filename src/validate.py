"""Run the data checks and the raw-vs-model reconciliation; write docs/validation.md."""
import pathlib
import sys

import duckdb

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from checks import CHECKS, FACT_TOTALS_SQL, ROOT, raw_totals  # noqa: E402

con = duckdb.connect(str(ROOT / "data" / "supply_chain.duckdb"), read_only=True)
lines = ["# Validation", "", "Generated by `src/validate.py`. The same checks run as pytest tests "
         "(`tests/test_data_quality.py`).", "", "## Data checks", "", "| Check | Expected | Got | Result |", "|---|---|---|---|"]
failed = 0
for name, sql, expect in CHECKS:
    got = con.sql(sql).fetchall()[0][0]
    ok = got == expect
    failed += not ok
    lines.append(f"| {name} | {expect} | {got} | {'pass' if ok else '**FAIL**'} |")

raw = raw_totals()
_rel = con.sql(FACT_TOTALS_SQL)
fact = dict(zip(_rel.columns, _rel.fetchall()[0]))
lines += ["", "## Reconciliation: raw CSV (Polars, no SQL) vs fact_order_lines", "",
          "| Measure | Raw CSV | fact_order_lines | Difference |", "|---|---|---|---|"]
for k, v in raw.items():
    diff = round(float(fact[k]) - float(v), 2)
    failed += abs(diff) > 0.05
    lines.append(f"| {k} | {v:,} | {fact[k]:,} | {diff} |")

w = con.sql("SELECT * FROM forecast_window").fetchall()[0]
lines += ["", "## Comparable window (detected in sql/04_regime.sql)", "",
          f"- First full week: {w[0]} (1 Jan 2015 is a Thursday, so the first 4 days are left out of weekly series).",
          f"- Break week: {w[2]}. From here the file has about 480 lines a week and one line per order "
          "(about 1,200 lines and 3 lines per order before).",
          f"- Last week used for weekly demand and the forecast: week starting {w[1]}.",
          f"- Last week in the file: {w[3]} (partial).", ""]
(ROOT / "docs" / "validation.md").write_text("\n".join(lines))
print("\n".join(lines))
if failed:
    sys.exit(f"{failed} check(s) failed")
