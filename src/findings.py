"""Run sql/findings.sql; write docs/findings_results.md (query + result) and docs/findings.json."""
import datetime as dt
import decimal
import json
import pathlib
import re

import duckdb

ROOT = pathlib.Path(__file__).resolve().parents[1]
con = duckdb.connect(str(ROOT / "data" / "supply_chain.duckdb"), read_only=True)
blocks = re.split(r"^-- name: ", (ROOT / "sql" / "findings.sql").read_text(), flags=re.M)[1:]


def fmt(v):
    if isinstance(v, float):
        return f"{v:,.2f}".rstrip("0").rstrip(".")
    if isinstance(v, int) and not isinstance(v, bool) and not 1900 <= v <= 2100:
        return f"{v:,}"
    return "" if v is None else str(v)


def jsonable(v):
    if isinstance(v, (dt.date, dt.datetime)):
        return v.isoformat()
    if isinstance(v, decimal.Decimal):
        return float(v)
    return v


out = ["# Findings: queries and results", "",
       "Generated by `src/findings.py` from `sql/findings.sql`. Do not edit by hand.", ""]
js = {}
for b in blocks:
    name, sql = b.split("\n", 1)
    name = name.strip()
    rel = con.sql(sql)
    cols, rows = rel.columns, rel.fetchall()
    js[name] = [{c: jsonable(v) for c, v in zip(cols, r)} for r in rows]
    out += [f"## {name}", "", "```sql", sql.strip(), "```", "",
            "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
    out.append("")
(ROOT / "docs" / "findings_results.md").write_text("\n".join(out))
(ROOT / "docs" / "findings.json").write_text(json.dumps(js, indent=1, default=str))
print("\n".join(out))
